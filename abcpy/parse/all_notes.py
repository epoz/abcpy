"""Conversion between abc note names and a linear pitch index (port of ``all-notes.js``)."""

all_pitches = [
    'C,,,', 'D,,,', 'E,,,', 'F,,,', 'G,,,', 'A,,,', 'B,,,',
    'C,,', 'D,,', 'E,,', 'F,,', 'G,,', 'A,,', 'B,,',
    'C,', 'D,', 'E,', 'F,', 'G,', 'A,', 'B,',
    'C', 'D', 'E', 'F', 'G', 'A', 'B',
    'c', 'd', 'e', 'f', 'g', 'a', 'b',
    "c'", "d'", "e'", "f'", "g'", "a'", "b'",
    "c''", "d''", "e''", "f''", "g''", "a''", "b''",
    "c'''", "d'''", "e'''", "f'''", "g'''", "a'''", "b'''",
]


def pitch_index(note_name):
    try:
        return all_pitches.index(note_name)
    except ValueError:
        return -1


def note_name(index):
    if 0 <= index < len(all_pitches):
        return all_pitches[index]
    return None
