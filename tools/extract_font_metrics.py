"""Developer tool: extract advance widths from TrueType fonts into abcpy/write/font_metrics.py.

usage: python3 tools/extract_font_metrics.py [/usr/share/fonts/truetype/liberation]
"""
import os
import struct
import sys

FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/liberation"
FONTS = {
    "sans": "LiberationSans", "serif": "LiberationSerif", "mono": "LiberationMono",
}
STYLES = {"normal": "Regular", "bold": "Bold", "italic": "Italic", "bolditalic": "BoldItalic"}
EXTRA = "♯♭♮°ø∆Δ–—‘’‚“”„…•€™←→↑↓√∞≈≠≤≥·×÷ˆ˜ƒ"
CODEPOINTS = list(range(0x20, 0x7F)) + list(range(0xA0, 0x250)) + [ord(c) for c in EXTRA]


def read_tables(data):
    num = struct.unpack(">H", data[4:6])[0]
    tables = {}
    for i in range(num):
        tag, _, off, length = struct.unpack(">4sIII", data[12 + 16 * i:28 + 16 * i])
        tables[tag.decode()] = (off, length)
    return tables


def parse(path):
    data = open(path, "rb").read()
    t = read_tables(data)
    head = t["head"][0]
    upem = struct.unpack(">H", data[head + 18:head + 20])[0]
    hhea = t["hhea"][0]
    ascent, descent = struct.unpack(">hh", data[hhea + 4:hhea + 8])
    num_hmetrics = struct.unpack(">H", data[hhea + 34:hhea + 36])[0]
    hmtx = t["hmtx"][0]
    advances = [struct.unpack(">H", data[hmtx + 4 * i:hmtx + 4 * i + 2])[0] for i in range(num_hmetrics)]
    cmap = t["cmap"][0]
    n = struct.unpack(">H", data[cmap + 2:cmap + 4])[0]
    sub = None
    for i in range(n):
        pid, eid, off = struct.unpack(">HHI", data[cmap + 4 + 8 * i:cmap + 12 + 8 * i])
        if pid == 3 and eid == 1:
            sub = cmap + off
    fmt = struct.unpack(">H", data[sub:sub + 2])[0]
    assert fmt == 4
    segx2 = struct.unpack(">H", data[sub + 6:sub + 8])[0]
    seg = segx2 // 2
    ends = struct.unpack(">%dH" % seg, data[sub + 14:sub + 14 + segx2])
    starts = struct.unpack(">%dH" % seg, data[sub + 16 + segx2:sub + 16 + 2 * segx2])
    deltas = struct.unpack(">%dh" % seg, data[sub + 16 + 2 * segx2:sub + 16 + 3 * segx2])
    ro_off = sub + 16 + 3 * segx2
    ranges = struct.unpack(">%dH" % seg, data[ro_off:ro_off + segx2])

    def glyph(cp):
        for i in range(seg):
            if starts[i] <= cp <= ends[i]:
                if ranges[i] == 0:
                    return (cp + deltas[i]) & 0xFFFF
                addr = ro_off + 2 * i + ranges[i] + 2 * (cp - starts[i])
                g = struct.unpack(">H", data[addr:addr + 2])[0]
                return (g + deltas[i]) & 0xFFFF if g else 0
        return 0

    widths = {}
    for cp in CODEPOINTS:
        g = glyph(cp)
        if g:
            adv = advances[min(g, len(advances) - 1)]
            widths[cp] = round(adv * 1000 / upem)
    return {"ascent": round(ascent * 1000 / upem), "descent": round(-descent * 1000 / upem), "widths": widths}


out = ['"""Advance widths (1/1000 em) of fonts metric-compatible with Arial/Helvetica, Times New Roman and',
       'Courier New, used to estimate the size of text when laying out music (generated by',
       'tools/extract_font_metrics.py from the Liberation fonts)."""', '', 'metrics = {']
for fam, base in FONTS.items():
    for style, suffix in STYLES.items():
        m = parse(os.path.join(FONT_DIR, "%s-%s.ttf" % (base, suffix)))
        w = m["widths"]
        out.append('    "%s-%s": {"ascent": %d, "descent": %d, "widths": {' % (fam, style, m["ascent"], m["descent"]))
        items = sorted(w.items())
        for i in range(0, len(items), 12):
            out.append("        " + " ".join("%d: %d," % kv for kv in items[i:i + 12]))
        out.append("    }},")
out.append("}")
open(os.path.join(os.path.dirname(__file__), "..", "abcpy", "write", "font_metrics.py"), "w").write("\n".join(out) + "\n")
print("ok")
